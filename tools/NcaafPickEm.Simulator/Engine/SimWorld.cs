using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Options;
using NcaafPickEm.Domain.Seasons;
using NcaafPickEm.Infrastructure.Data;
using NcaafPickEm.Simulator.Catalog;
using NcaafPickEm.Simulator.Engine.Views;

namespace NcaafPickEm.Simulator.Engine;

/// <summary>
/// The simulated world, and the only thing the dashboard talks to (P11-01). Every action takes
/// one gate - so a button press and an autoplay tick never interleave - and runs its steps each in
/// a fresh DI scope, the way a request or a job run would, over the app's own services.
/// </summary>
/// <remarks>
/// Split by area: this file has the plumbing, the sandbox, settings and jobs; the calendar and
/// week lifecycle, games and scores, and players and picks each have their own part.
/// </remarks>
public sealed partial class SimWorld
{
    private readonly IServiceScopeFactory _scopes;
    private readonly SimDatabaseStatus _status;
    private readonly SimActivity _activity;
    private readonly TimeProvider _timeProvider;
    private readonly SimulatorOptions _options;
    private readonly ILogger<SimWorld> _logger;
    private readonly SemaphoreSlim _gate = new(1, 1);

    /// <summary>Creates the world. Singleton.</summary>
    public SimWorld(
        IServiceScopeFactory scopes,
        SimDatabaseStatus status,
        SimActivity activity,
        TimeProvider timeProvider,
        IOptions<SimulatorOptions> options,
        ILogger<SimWorld> logger)
    {
        ArgumentNullException.ThrowIfNull(options);

        _scopes = scopes;
        _status = status;
        _activity = activity;
        _timeProvider = timeProvider;
        _options = options.Value;
        _logger = logger;
    }

    /// <summary>The season a database with no simulator state yet simulates.</summary>
    public int DefaultSeasonYear => _options.SeasonYear > 0 ? _options.SeasonYear : _timeProvider.GetUtcNow().Year;

    /// <summary>Where the app runs, for links.</summary>
    public string AppBaseUrl => _options.AppBaseUrl.TrimEnd('/');

    /// <summary>The dashboard's snapshot. Read-only; does not take the gate.</summary>
    public Task<SimSnapshot> ReadAsync(CancellationToken cancellationToken) =>
        InScopeAsync(services => services.GetRequiredService<SnapshotReader>().ReadAsync(DefaultSeasonYear, _status, cancellationToken));

    /// <summary>Every team, for pickers.</summary>
    public Task<IReadOnlyList<SimTeamOption>> ReadTeamsAsync(CancellationToken cancellationToken) =>
        InScopeAsync(services => services.GetRequiredService<SnapshotReader>().ReadTeamsAsync(cancellationToken));

    /// <summary>
    /// One click to a playable league: the catalog, a calendar with <see cref="SandboxRequest.StartWeek"/>
    /// current from now (unless the season is already under way), a slate whose first kickoff is
    /// minutes away, the tester as commissioner, the players joined through invites, default rules,
    /// and the week's set generated by the app's own Sunday job.
    /// </summary>
    public Task<SimLog> CreateSandboxAsync(SandboxRequest request, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(request);

        return RunAsync("Create sandbox", async (log, token) =>
        {
            int added = await InScopeAsync(services =>
                services.GetRequiredService<CatalogDesk>().EnsureCatalogAsync(TeamCatalog.Default, token)).ConfigureAwait(false);
            if (added > 0)
            {
                log.Note($"catalog: {added} teams and their conferences written");
            }

            SimState state = await LoadStateAsync(token).ConfigureAwait(false);
            state.AutoPlay = request.AutoPlay;
            state.GameMinutes = Math.Clamp(request.GameMinutes, 1, 600);
            state.LockLeadMinutes = Math.Clamp(request.LockInMinutes, 1, 7 * 24 * 60);
            state.Slate = (request.Slate ?? state.Slate).Normalized();
            await SaveStateAsync(state, token).ConfigureAwait(false);

            CurrentWeek? current = await CurrentWeekAsync(state, token).ConfigureAwait(false);
            if (current is { State: SeasonState.InSeason } inSeason)
            {
                log.Note($"calendar: the season is under way; staying on week {inSeason.Week}");
            }
            else
            {
                // The league does not exist yet; its set is generated once it does, below.
                await EnterWeekAsync(state, Math.Clamp(request.StartWeek, SimCalendarLayout.FirstWeek, SimCalendarLayout.LastRegularWeek), log, token, generateSets: false)
                    .ConfigureAwait(false);
            }

            Guid testerId = await InScopeAsync(async services =>
                (await services.GetRequiredService<PeopleDesk>().EnsureUserAsync(request.TesterName, token).ConfigureAwait(false)).Id)
                .ConfigureAwait(false);

            state = await LoadStateAsync(token).ConfigureAwait(false);
            state.TesterUserId = testerId;
            await SaveStateAsync(state, token).ConfigureAwait(false);

            Guid leagueId = await InScopeAsync(services => services.GetRequiredService<PeopleDesk>()
                .CreateLeagueAsync(testerId, request.LeagueName, state.SeasonYear, token)).ConfigureAwait(false);
            log.Note($"league: {request.LeagueName} created, {request.TesterName} is commissioner (sign in as '{PeopleDesk.SlugFor(request.TesterName)}')");

            await InScopeAsync(services => services.GetRequiredService<PeopleDesk>()
                .ApplyDefaultRulesAsync(leagueId, request.Conference, token)).ConfigureAwait(false);
            log.Note($"rules: Top 25 + {request.Conference} conference games; +20 for lines inside {SlateBuilder.CloseSpread}, +15 for conference games");

            foreach (string name in request.Players.Where(name => !string.IsNullOrWhiteSpace(name)).Distinct(StringComparer.OrdinalIgnoreCase))
            {
                string outcome = await InScopeAsync(async services =>
                {
                    PeopleDesk people = services.GetRequiredService<PeopleDesk>();
                    Guid userId = (await people.EnsureUserAsync(name, token).ConfigureAwait(false)).Id;
                    return userId == testerId ? "is you" : await people.JoinAsync(leagueId, userId, token).ConfigureAwait(false);
                }).ConfigureAwait(false);
                log.Note($"player: {name} {outcome}");
            }

            await RunJobStepAsync("EnsureCurrentWeekSets", log, token).ConfigureAwait(false);
            await NoteLocksAsync(state, log, token).ConfigureAwait(false);
        }, cancellationToken);
    }

    /// <summary>Empties the database back to its players (see <see cref="WipeDesk"/>) and forgets every plan.</summary>
    public Task<SimLog> WipeAsync(CancellationToken cancellationToken) =>
        RunAsync("Wipe", async (log, token) =>
        {
            await InScopeAsync(services => services.GetRequiredService<WipeDesk>().WipeAsync(token)).ConfigureAwait(false);

            SimState state = await LoadStateAsync(token).ConfigureAwait(false);
            state.Plans.Clear();
            state.TesterUserId = null;
            await SaveStateAsync(state, token).ConfigureAwait(false);

            log.Note("every league, game, poll, line and calendar week deleted; players kept");
        }, cancellationToken);

    /// <summary>Turns autoplay on or off and sets how long a game lasts.</summary>
    public Task<SimLog> SetAutoplayAsync(bool on, int gameMinutes, CancellationToken cancellationToken) =>
        RunAsync("Autoplay", async (log, token) =>
        {
            SimState state = await LoadStateAsync(token).ConfigureAwait(false);
            int minutes = Math.Clamp(gameMinutes, 1, 600);
            DateTimeOffset nowUtc = _timeProvider.GetUtcNow();

            if (on && (!state.AutoPlay || minutes != state.GameMinutes))
            {
                // Re-anchor every live game at the score it has, so neither turning autoplay back on
                // nor a new game length rewinds or jumps a score.
                await ReanchorLiveGamesAsync(state, nowUtc, minutes, token).ConfigureAwait(false);
            }

            state.AutoPlay = on;
            state.GameMinutes = minutes;
            await SaveStateAsync(state, token).ConfigureAwait(false);
            log.Note(on ? $"on: {minutes}-minute games" : "off: games only move when you move them");
        }, cancellationToken);

    /// <summary>Sets how far ahead a new week's first kickoff is and how its slate is shaped.</summary>
    public Task<SimLog> SetWeekDefaultsAsync(int lockLeadMinutes, SlateOptions slate, CancellationToken cancellationToken) =>
        RunAsync("New-week defaults", async (log, token) =>
        {
            ArgumentNullException.ThrowIfNull(slate);

            SimState state = await LoadStateAsync(token).ConfigureAwait(false);
            state.LockLeadMinutes = Math.Clamp(lockLeadMinutes, 1, 7 * 24 * 60);
            state.Slate = slate.Normalized();
            await SaveStateAsync(state, token).ConfigureAwait(false);
            log.Note($"new weeks lock {state.LockLeadMinutes} min after they start; slates of {state.Slate.GameCount}, " +
                $"{state.Slate.GamesPerSlot} per window every {state.Slate.SlotMinutes} min");
        }, cancellationToken);

    /// <summary>Runs one of the app's jobs now (see <see cref="JobDesk.Jobs"/>).</summary>
    public Task<SimLog> RunJobAsync(string name, CancellationToken cancellationToken) =>
        RunAsync($"Run {name}", (log, token) => RunJobStepAsync(name, log, token), cancellationToken);

    /// <summary>
    /// Runs an action under the gate and records its log. Refused outright while the database is
    /// not the simulator's; an exception becomes the log's last line rather than a crash.
    /// </summary>
    private async Task<SimLog> RunAsync(string title, Func<SimLog, CancellationToken, Task> body, CancellationToken cancellationToken)
    {
        var log = new SimLog(title, _timeProvider.GetUtcNow());

        if (!_status.IsUsable)
        {
            log.Fail(_status.Problem ?? "The database is not usable.");
            return log;
        }

        await _gate.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            await body(log, cancellationToken).ConfigureAwait(false);
        }
        catch (Exception exception) when (exception is not OperationCanceledException)
        {
            log.Fail(exception.Message);
            _logger.LogWarning(exception, "Simulator action {Action} failed", title);
        }
        finally
        {
            _gate.Release();
        }

        _activity.Add(log);
        return log;
    }

    private async Task<T> InScopeAsync<T>(Func<IServiceProvider, Task<T>> step)
    {
        AsyncServiceScope scope = _scopes.CreateAsyncScope();
        await using (scope.ConfigureAwait(false))
        {
            return await step(scope.ServiceProvider).ConfigureAwait(false);
        }
    }

    private async Task InScopeAsync(Func<IServiceProvider, Task> step)
    {
        AsyncServiceScope scope = _scopes.CreateAsyncScope();
        await using (scope.ConfigureAwait(false))
        {
            await step(scope.ServiceProvider).ConfigureAwait(false);
        }
    }

    private Task<SimState> LoadStateAsync(CancellationToken cancellationToken) =>
        InScopeAsync(services => services.GetRequiredService<SimStateStore>().LoadAsync(DefaultSeasonYear, cancellationToken));

    private Task SaveStateAsync(SimState state, CancellationToken cancellationToken) =>
        InScopeAsync(services => services.GetRequiredService<SimStateStore>().SaveAsync(state, cancellationToken));

    private Task<CurrentWeek?> CurrentWeekAsync(SimState state, CancellationToken cancellationToken) =>
        InScopeAsync(services => services.GetRequiredService<CalendarDesk>().CurrentAsync(state.SeasonYear, cancellationToken));

    /// <summary>The current week, or a failed log line when the season has no calendar yet.</summary>
    private async Task<int?> RequireWeekAsync(SimState state, SimLog log, CancellationToken cancellationToken)
    {
        CurrentWeek? current = await CurrentWeekAsync(state, cancellationToken).ConfigureAwait(false);
        if (current is CurrentWeek week)
        {
            return week.Week;
        }

        log.Fail("there is no calendar yet: create a sandbox or start a week first");
        return null;
    }

    private async Task RunJobStepAsync(string name, SimLog log, CancellationToken cancellationToken, bool record = true)
    {
        string outcome = await InScopeAsync(services => services.GetRequiredService<JobDesk>().RunAsync(name, cancellationToken))
            .ConfigureAwait(false);
        if (record)
        {
            log.Note($"job: {outcome}");
        }
    }

    /// <summary>Notes each league's set this week: size, and when it locks.</summary>
    private async Task NoteLocksAsync(SimState state, SimLog log, CancellationToken cancellationToken)
    {
        CurrentWeek? current = await CurrentWeekAsync(state, cancellationToken).ConfigureAwait(false);
        if (current is not CurrentWeek week)
        {
            return;
        }

        var sets = await InScopeAsync(services =>
        {
            AppDbContext database = services.GetRequiredService<AppDbContext>();
            return database.WeekGameSets
                .AsNoTracking()
                .Where(set => set.Week == week.Week && set.League!.SeasonYear == state.SeasonYear)
                .Select(set => new
                {
                    League = set.League!.Name,
                    set.LockAtUtc,
                    set.LockedUtc,
                    Games = database.WeekGameSetGames.Count(row => row.WeekGameSetId == set.Id && !row.IsRemoved),
                })
                .ToListAsync(cancellationToken);
        }).ConfigureAwait(false);

        DateTimeOffset nowUtc = _timeProvider.GetUtcNow();
        foreach (var set in sets)
        {
            string when = set.LockedUtc is not null
                ? "locked"
                : set.LockAtUtc is DateTime lockAt
                    ? $"locks {SimFormat.Relative(SimFormat.Utc(lockAt), nowUtc)} ({SimFormat.Eastern(SimFormat.Utc(lockAt))})"
                    : "no lock (no games)";
            log.Note($"set: {set.League} week {week.Week}, {set.Games} game(s), {when}");
        }
    }
}
